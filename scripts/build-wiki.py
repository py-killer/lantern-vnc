#!/usr/bin/env python3
"""Build the tracked Pages wiki from docs/wiki/*.md without modifying sources.

Build-time requirement: Python-Markdown 3.7 (not an app/runtime dependency).
From the repository root, install locally and build with:

    python3 -m pip install --target work/wiki-tools Markdown==3.7
    python3 scripts/build-wiki.py

The script also finds ../work/wiki-tools for a shared parent workspace.
Generated HTML/CSS is served directly by Pages; visitors need no Python or JS.
"""

from pathlib import Path
import html
import re
import sys
from urllib.parse import quote

ROOT = Path(__file__).resolve().parent.parent
WIKI = ROOT / "docs/wiki"
REPOSITORY = "https://github.com/py-killer/lantern-vnc"
PUBLIC_WIKI = "https://py-killer.github.io/lantern-vnc/wiki/"

for package_path in (ROOT / "work/wiki-tools", ROOT.parent / "work/wiki-tools"):
    if package_path.is_dir():
        sys.path.insert(0, str(package_path))
        break
try:
    import markdown
except ImportError as error:
    raise SystemExit(
        "Build-time dependency missing: install Markdown==3.7 locally with\n"
        "python3 -m pip install --target work/wiki-tools Markdown==3.7"
    ) from error
if markdown.__version__ != "3.7":
    raise SystemExit("Use pinned build-time renderer Markdown==3.7 for reproducible HTML.")

PAGES = [
    ("Home.md", "index.html", "Overview", "Your guide to a clearer connection."),
    ("Getting-Started.md", "getting-started.html", "Getting started", "Open Lantern, connect, and save your usual devices."),
    ("Display-and-Navigation.md", "display-and-navigation.html", "Display & navigation", "Choose a readable view and reach every edge."),
    ("Troubleshooting.md", "troubleshooting.html", "Troubleshooting", "Find a useful next step when something feels off."),
    ("FAQ.md", "faq.html", "FAQ", "Compatibility, privacy, and the practical details."),
]
PAGE_LINKS = {source: output for source, output, _, _ in PAGES}


def escape(text):
    return html.escape(text, quote=True)


def rewrite_links(text, source):
    def rewrite(match):
        target = match.group(1)
        if "://" in target or target.startswith(("#", "mailto:")):
            return match.group(0)
        path, marker, anchor = target.partition("#")
        resolved = (source.parent / path).resolve()
        if not resolved.is_file():
            raise ValueError(f"Missing Markdown link target in {source.name}: {target}")
        if resolved.parent == WIKI and resolved.name in PAGE_LINKS:
            result = PAGE_LINKS[resolved.name]
        else:
            relative = resolved.relative_to(ROOT).as_posix()
            result = f"{REPOSITORY}/blob/main/{quote(relative, safe='/')}"
        if marker:
            result += "#" + anchor
        return "](" + result + ")"

    return re.sub(r"\]\(([^)]+)\)", rewrite, text)


def navigation(current, label):
    links = []
    for source, output, title, _ in PAGES:
        active = ' aria-current="page"' if source == current else ""
        links.append(f'<a href="{output}"{active}>{escape(title)}</a>')
    return f'<nav class="guide-links" aria-label="{escape(label)}">' + "".join(links) + "</nav>"


def render_page(index, source_name, output, label, description):
    source = WIKI / source_name
    engine = markdown.Markdown(
        extensions=["tables", "fenced_code", "toc", "sane_lists"],
        extension_configs={"toc": {"toc_depth": "2-3"}},
        output_format="html5",
    )
    body = engine.convert(rewrite_links(source.read_text(), source))
    body = body.replace("<table>", '<div class="table-scroll" role="region" aria-label="Reference table" tabindex="0"><table>')
    body = body.replace("</table>", "</table></div>")
    source_url = f"{REPOSITORY}/blob/main/docs/wiki/{source_name}"
    edit_url = f"{REPOSITORY}/edit/main/docs/wiki/{source_name}"
    previous = PAGES[index - 1] if index > 0 else None
    following = PAGES[index + 1] if index + 1 < len(PAGES) else None
    paging = ""
    if previous:
        paging += f'<a href="{previous[1]}"><span>Previous guide</span><strong>{escape(previous[2])}</strong></a>'
    if following:
        paging += f'<a class="next-guide" href="{following[1]}"><span>Next guide</span><strong>{escape(following[2])}</strong></a>'
    toc = f'<aside class="page-contents" aria-label="On this page"><p>ON THIS PAGE</p>{engine.toc}</aside>' if engine.toc_tokens else ""
    return f'''<!doctype html>
<!-- Generated by scripts/build-wiki.py from {escape(source_name)}. Edit the Markdown source. -->
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <meta name="theme-color" content="#f3f7f6">
  <meta name="description" content="{escape(description)} Lantern VNC's community Wiki for its native Mac viewer.">
  <title>{escape(label)} · Lantern VNC Wiki</title>
  <link rel="canonical" href="{PUBLIC_WIKI}{'' if output == 'index.html' else output}">
  <link rel="stylesheet" href="wiki.css">
</head>
<body>
  <a class="skip-link" href="#content">Skip to the guide</a>
  <header class="wiki-header"><div class="header-inner">
    <a class="brand" href="index.html" aria-label="Lantern VNC Wiki home"><svg width="34" height="34" viewBox="0 0 36 36" aria-hidden="true"><rect width="36" height="36" rx="11" fill="currentColor"/><rect x="8" y="8" width="20" height="15" rx="3" fill="none" stroke="#fff" stroke-width="1.7"/><path d="M13 28h10m-5-5v5" stroke="#fff" stroke-width="1.7" stroke-linecap="round"/><circle cx="23" cy="13" r="2.5" fill="#9be0d1"/></svg><span>Lantern<span class="wiki-word">Wiki</span></span></a>
    <nav class="header-links" aria-label="Project links"><a href="../">The app</a><a href="{REPOSITORY}">GitHub</a></nav>
  </div></header>
  <div class="wiki-layout">
    <aside class="sidebar"><p class="nav-caption">THE GUIDES</p>{navigation(source_name, "Wiki guides")}<div class="sidebar-resources"><p class="nav-caption">THE PROJECT</p><a href="{REPOSITORY}/blob/main/CHANGELOG.md">Changelog</a><a href="{REPOSITORY}/blob/main/docs/RELEASE_CHECKLIST.md">Release checklist</a><a href="{REPOSITORY}/blob/main/CONTRIBUTING.md">Contributing</a><a href="{REPOSITORY}/blob/main/SECURITY.md">Security</a></div><div class="sidebar-note"><strong>A little help,<br>close to hand.</strong><p>Free to use. Open to improve.</p></div></aside>
    <main class="content-column" id="content">
      <details class="mobile-navigation"><summary>Browse the guides</summary>{navigation(source_name, "Mobile Wiki guides")}</details>
      <div class="page-intro"><span class="eyebrow">LANTERN VNC · COMMUNITY WIKI</span><span class="preview-label">Preview documentation</span></div>
      <article class="guide-content">{body}</article>
      <nav class="guide-paging" aria-label="More guides">{paging}</nav>
      <div class="page-actions"><a href="{edit_url}">Improve this guide</a><a href="{source_url}">Read the Markdown</a><a href="{REPOSITORY}/issues/new/choose">Share feedback</a></div>
    </main>
    {toc}
  </div>
  <footer class="wiki-footer"><p>A native window into your other computer.</p><nav aria-label="Footer links"><a href="../">Lantern VNC</a><a href="{REPOSITORY}/blob/main/CODE_OF_CONDUCT.md">Community conduct</a><a href="{REPOSITORY}/blob/main/LICENSE">GPL-2.0-or-later</a></nav></footer>
</body>
</html>
'''


def main():
    for index, page in enumerate(PAGES):
        output = WIKI / page[1]
        output.write_text(render_page(index, *page))
        print(output.relative_to(ROOT))
    print("Built 5 static Wiki pages with Python-Markdown 3.7; Markdown sources unchanged.")


if __name__ == "__main__":
    main()
